import React from "react"
import { Card } from "antd"
import GuideHeader from "../../../components/GuideHeader"
import * as styles from "../../../styles.module.scss"

function UserPathGuide() {
  return (
    <Card>
      <GuideHeader title="用户路径分析说明" />
      <div className={styles.guideContent}>
        <h3>用来解决什么问题</h3>
        <p>查看同一用户会话内，所选事件之间如何流转。路径图用于发现常见的下一步或前置行为；需要验证固定步骤的转化率时，可使用漏斗分析。</p>

        <h3>完成一次查询</h3>
        <ol>
          <li>在“事件选择”中至少选择两个已经采集的事件，定义本次关注的行为范围。</li>
          <li>在“事件定义”中选择其中一个事件，并指定它作为“起点”或“终点”。每次查询选择一个方向。</li>
          <li>按需设置全局筛选，选择时间范围后点击“查询”。当前页面由所选事件限定分析范围，没有单独的路径深度设置。</li>
          <li>在桑基图中查看节点和连线，悬停查看事件名称、流转次数；可下载图表图片，也可通过导出任务获取结果数据。</li>
        </ol>

        <h3>如何理解路径</h3>
        <ul>
          <li><strong>会话范围</strong>：按用户与会话组合整理事件序列，不把不同会话直接连接成一条路径。缺少会话标识的数据不参与路径计算。</li>
          <li><strong>起点分析</strong>：选取包含起点事件的会话，并截取从第一次起点事件开始的流转。</li>
          <li><strong>终点分析</strong>：选取包含终点事件的会话，并截取到最后一次终点事件为止的流转。</li>
          <li><strong>相邻关系</strong>：先保留所选事件，再按发生时间连接相邻事件。没有选中的中间行为不会展示，因此图中的相邻不代表原始记录中紧挨着发生。</li>
          <li><strong>流转次数</strong>：同一用户、同一会话内的同一事件对只计一次。节点提示中的“总流出次数”是其流出连线的合计，不是独立用户数。</li>
          <li><strong>图表展示</strong>：桑基图只展示流转次数至少为 5 的连线，小样本流转可能在查询结果中存在，但不在图上连线。</li>
        </ul>

        <h3>保存与导出</h3>
        <p>可将当前配置保存为看板，在首页查看；图表下载用于保存当前视图，数据导出通过异步任务生成文件。</p>

        <h3>常见问题</h3>
        <ul>
          <li><strong>有事件但图中没有连线</strong>：检查是否在同一会话内发生、是否包含选定的起点或终点，以及流转次数是否达到图表展示门槛。</li>
          <li><strong>切换事件后起点或终点被清空</strong>：作为起点或终点的事件必须仍在所选事件列表中，移除后需要重新指定。</li>
          <li><strong>路径与漏斗数量不同</strong>：路径统计相邻事件对，漏斗统计按步骤完成的分析对象，两者不能直接等同。</li>
        </ul>
      </div>
    </Card>
  )
}

export default UserPathGuide
