function Guide() {
  const { pageKey } = useParams<{ pageKey: string }>()
  const navigate = useNavigate()

  const guide = useMemo(() => {
    if (!pageKey) return null
    return guideContent[pageKey]
  }, [pageKey])

  const handleBack = () => {
    navigate(-1)
  }

  if (!guide) {
    return (
      <div className={styles.container}>
        <PageHeader title="页面说明" />
        <Card>
          <p>未找到对应的页面说明，请检查URL是否正确。</p>
          <Button onClick={handleBack}>返回</Button>
        </Card>
      </div>
    )
  }

  return (
    <div className={styles.container}>
      <PageHeader
        title={guide.title}
        extra={
          <Button
            icon={<ArrowLeft theme="outline" size="16" fill="#000000" />}
            onClick={handleBack}
          >
            返回
          </Button>
        }
      />
      <Card className={styles.card}>
        {guide.content}
      </Card>
    </div>
  )
}

export default Guide
